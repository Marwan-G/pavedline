// Build CSS variables and a typed object from docs/design/tokens.json (step 7's export).
// Format: {"light": {"<group>": {"<name>": "<value>"}}, "dark": {same names}}. Names must match in both modes.
// node scripts/build.mjs           writes src/generated.ts
// node scripts/build.mjs --check   fails when the committed file is stale
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const source = resolve(here, '../../../docs/design/tokens.json')
const target = resolve(here, '../src/generated.ts')

function flatten(node, prefix = []) {
  const out = {}
  for (const [key, value] of Object.entries(node)) {
    if (value !== null && typeof value === 'object')
      Object.assign(out, flatten(value, [...prefix, key]))
    else out[[...prefix, key].join('-')] = String(value)
  }
  return out
}

export function render(tokens) {
  const light = flatten(tokens.light ?? {})
  const dark = flatten(tokens.dark ?? {})
  const names = Object.keys(light).sort()
  const darkNames = Object.keys(dark).sort()
  if (names.join('|') !== darkNames.join('|')) {
    throw new Error('tokens.json: light and dark must define the same names')
  }
  const block = (selector, map) =>
    `${selector} {\n${names.map((n) => `  --${n}: ${map[n]};`).join('\n')}\n}\n`
  const css = `${block(':root', light)}\n@media (prefers-color-scheme: dark) {\n${block(
    ':root',
    dark,
  )
    .split('\n')
    .map((l) => (l ? `  ${l}` : l))
    .join('\n')}}\n`
  return [
    '// Generated by scripts/build.mjs from docs/design/tokens.json. Do not edit.',
    `export const tokens = ${JSON.stringify({ light, dark }, null, 2)} as const`,
    '',
    `export const css = ${JSON.stringify(css)}`,
    '',
  ].join('\n')
}

if (!existsSync(source)) {
  // No tokens yet (step 7 not done): the shipped placeholder is fine. Generated output without its source is not.
  const isPlaceholder =
    existsSync(target) && readFileSync(target, 'utf8').startsWith('// Placeholder.')
  if (process.argv.includes('--check') && (isPlaceholder || !existsSync(target))) {
    console.log('tokens: no docs/design/tokens.json yet (written at step 7); nothing to check')
    process.exit(0)
  }
  console.error(
    `tokens: ${source} does not exist but generated output does (or a build was asked for)`,
  )
  process.exit(1)
}
const next = render(JSON.parse(readFileSync(source, 'utf8')))
if (process.argv.includes('--check')) {
  if (!existsSync(target) || readFileSync(target, 'utf8') !== next) {
    console.error('tokens: src/generated.ts is out of date. Run: pnpm --filter @app/tokens build')
    process.exit(1)
  }
  console.log('tokens: generated file is current')
} else {
  writeFileSync(target, next)
}
